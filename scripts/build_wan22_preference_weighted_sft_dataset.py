"""Build a preference-weighted Wan/Musubi SFT dataset from proxy pairs.

This is not diffusion DPO. It is the cheap bridge experiment: turn the existing
TRIBE/BMD top-vs-median/top-vs-bottom pair data into a winner-only video-caption
dataset where high-margin winners appear more often. That lets us test whether
preference-weighted proxy distillation improves over the existing one-winner-per
seed LoRA before spending more on a true pairwise trainer.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np

DEFAULT_PAIRS = Path(
    "data/training/wan22_lora_proxy_train_50x4_tribe_preferences_margin05.jsonl"
)
DEFAULT_OUT_DIR = Path("data/training/wan22_lora_pref_weighted_winners_50_margin05")


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(path)
    rows = []
    for line_no, line in enumerate(path.read_text().splitlines(), start=1):
        if not line.strip():
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise ValueError(f"invalid JSON on {path}:{line_no}") from exc
    return rows


def _link_or_copy(src: Path, dst: Path, *, copy: bool, overwrite: bool) -> str:
    if dst.exists():
        if not overwrite:
            return "existing"
        dst.unlink()
    dst.parent.mkdir(parents=True, exist_ok=True)
    if copy:
        shutil.copy2(src, dst)
        return "copy"
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


def _repeat_count(margin: float, *, margin_unit: float, max_repeats: int) -> int:
    if margin_unit <= 0:
        raise ValueError("--margin-unit must be > 0")
    return max(1, min(max_repeats, int(np.ceil(margin / margin_unit))))


def _write_dataset_toml(
    path: Path,
    *,
    videos_dir: Path,
    cache_dir: Path,
    resolution: tuple[int, int],
    target_frames: int,
    source_fps: float,
) -> None:
    width, height = resolution
    path.write_text(
        "\n".join(
            [
                "# Auto-generated by scripts/build_wan22_preference_weighted_sft_dataset.py",
                "# Winner-only dataset weighted by TRIBE/BMD proxy preference margins.",
                "",
                "[general]",
                f"resolution = [{width}, {height}]",
                'caption_extension = ".txt"',
                "batch_size = 1",
                "enable_bucket = true",
                "bucket_no_upscale = false",
                "",
                "[[datasets]]",
                f'video_directory = "{videos_dir.resolve()}"',
                f'cache_directory = "{cache_dir.resolve()}"',
                f"target_frames = [{target_frames}]",
                'frame_extraction = "head"',
                f"source_fps = {source_fps:.1f}",
                "",
            ]
        )
    )


def _safe_stem(text: str) -> str:
    return "".join(c if c.isalnum() or c in "-_." else "_" for c in text)


def build_dataset(
    pairs: list[dict[str, Any]],
    *,
    out_dir: Path,
    project_root: Path,
    resolution: tuple[int, int],
    target_frames: int,
    source_fps: float,
    margin_unit: float,
    max_repeats: int,
    copy: bool,
    overwrite: bool,
) -> dict[str, Any]:
    if not pairs:
        raise ValueError("no preference pairs supplied")

    videos_dir = out_dir / "videos"
    cache_dir = out_dir / "cache_latents"
    cache_text_dir = out_dir / "cache_text"
    out_dir.mkdir(parents=True, exist_ok=True)
    videos_dir.mkdir(parents=True, exist_ok=True)
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_text_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    seed_counts: Counter[str] = Counter()
    label_counts: Counter[str] = Counter()
    pair_counts_by_seed: Counter[str] = Counter()

    sorted_pairs = sorted(
        pairs,
        key=lambda pair: (str(pair.get("seed", "")), str(pair.get("pair_id", ""))),
    )
    for pair in sorted_pairs:
        seed = str(pair["seed"])
        chosen = pair["chosen"]
        label = str(chosen["label"])
        prompt = str(pair.get("prompt") or "").replace("\n", " ").strip()
        if not prompt:
            raise ValueError(f"missing prompt for pair {pair.get('pair_id')}")
        src = project_root / str(chosen["video"])
        if not src.exists():
            raise FileNotFoundError(src)

        margin = float(pair["margin"])
        repeats = _repeat_count(
            margin,
            margin_unit=margin_unit,
            max_repeats=max_repeats,
        )
        pair_counts_by_seed[seed] += 1

        for repeat_idx in range(repeats):
            label_counts[label] += 1
            seed_counts[seed] += 1
            row_idx = len(rows) + 1
            stem = _safe_stem(f"{row_idx:04d}_{seed}_{label}_r{repeat_idx:02d}")
            dest_video = videos_dir / f"{stem}.mp4"
            link_mode = _link_or_copy(src, dest_video, copy=copy, overwrite=overwrite)
            caption_file = videos_dir / f"{stem}.txt"
            caption_file.write_text(prompt + "\n")
            rows.append(
                {
                    "row": row_idx,
                    "pair_id": pair.get("pair_id"),
                    "seed": seed,
                    "chosen_label": label,
                    "chosen_score": float(chosen["score"]),
                    "rejected_label": pair["rejected"]["label"],
                    "rejected_score": float(pair["rejected"]["score"]),
                    "margin": margin,
                    "repeat_idx": repeat_idx,
                    "repeat_count_for_pair": repeats,
                    "video": str(dest_video),
                    "video_abs": str(dest_video.resolve()),
                    "caption_file": str(caption_file),
                    "prompt": prompt,
                    "source_video": str(src),
                    "link_mode": link_mode,
                }
            )

    metadata_jsonl = out_dir / "metadata.jsonl"
    metadata_jsonl.write_text(
        "".join(
            json.dumps(
                {"video_path": row["video_abs"], "caption": row["prompt"]},
                sort_keys=True,
            )
            + "\n"
            for row in rows
        )
    )

    dataset_toml = out_dir / "dataset.toml"
    _write_dataset_toml(
        dataset_toml,
        videos_dir=videos_dir,
        cache_dir=cache_dir,
        resolution=resolution,
        target_frames=target_frames,
        source_fps=source_fps,
    )

    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(rows, indent=2))

    margins = [float(pair["margin"]) for pair in sorted_pairs]
    summary = {
        "out_dir": str(out_dir),
        "n_pairs": len(sorted_pairs),
        "n_unique_seeds": len(pair_counts_by_seed),
        "n_unique_chosen_labels": len(label_counts),
        "n_training_items": len(rows),
        "dataset_toml": str(dataset_toml),
        "metadata_jsonl": str(metadata_jsonl),
        "videos_dir": str(videos_dir),
        "cache_dir": str(cache_dir),
        "cache_text_dir": str(cache_text_dir),
        "resolution": list(resolution),
        "target_frames": target_frames,
        "source_fps": source_fps,
        "margin_unit": margin_unit,
        "max_repeats": max_repeats,
        "pair_margin_mean": float(np.mean(margins)),
        "pair_margin_median": float(np.median(margins)),
        "pair_margin_min": float(np.min(margins)),
        "pair_margin_max": float(np.max(margins)),
        "max_items_for_one_seed": max(seed_counts.values()),
        "objective": "tribe_bmd_memorability_proxy_preference_weighted_sft",
        "warning": "Winner-only proxy distillation, not diffusion DPO and not human labels.",
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    (out_dir / "README.md").write_text(
        "\n".join(
            [
                "# Wan2.2 TRIBE/BMD Preference-Weighted Winners",
                "",
                "This is a cheap proxy-distillation dataset built from TRIBE/BMD preference pairs.",
                "It repeats chosen videos according to pair margin and omits rejected videos.",
                "Use it as a bridge experiment before implementing a true pairwise diffusion-DPO trainer.",
                "",
                f"- Preference pairs: {summary['n_pairs']}",
                f"- Unique seeds: {summary['n_unique_seeds']}",
                f"- Training items after weighting: {summary['n_training_items']}",
                f"- Median margin: {summary['pair_margin_median']:.4f}",
                "",
                "Main files:",
                "- `dataset.toml`: Musubi video-caption dataset config",
                "- `manifest.json`: audit trail for repeated winners and preference margins",
                "- `metadata.jsonl`: video/caption rows",
                "",
            ]
        )
    )
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pairs-jsonl", type=Path, default=DEFAULT_PAIRS)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--project-root", type=Path, default=Path.cwd())
    parser.add_argument("--resolution", nargs=2, type=int, default=(640, 352))
    parser.add_argument("--target-frames", type=int, default=81)
    parser.add_argument("--source-fps", type=float, default=24.0)
    parser.add_argument("--margin-unit", type=float, default=1.0)
    parser.add_argument("--max-repeats", type=int, default=3)
    parser.add_argument("--copy", action="store_true")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    if (args.target_frames - 1) % 4 != 0:
        raise ValueError("--target-frames must be N*4+1 for Wan video training")
    if args.max_repeats < 1:
        raise ValueError("--max-repeats must be >= 1")

    pairs = _read_jsonl(args.pairs_jsonl)
    summary = build_dataset(
        pairs,
        out_dir=args.out_dir,
        project_root=args.project_root,
        resolution=(args.resolution[0], args.resolution[1]),
        target_frames=args.target_frames,
        source_fps=args.source_fps,
        margin_unit=args.margin_unit,
        max_repeats=args.max_repeats,
        copy=args.copy,
        overwrite=args.overwrite,
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
