"""Build a Wan/Musubi SFT dataset from TRIBE-selected winner clips.

The input report is the scored best-of-N matrix. For each BMD seed, this script
selects the highest TRIBE/BMD projection variant and writes a compact
video-caption dataset that Musubi can cache/train.

This is proxy supervision: it distills the TRIBE/BMD-selected winner clips, not
direct human labels.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
from pathlib import Path
from typing import Any

import numpy as np

DEFAULT_REPORT = Path(
    "data/reports/wan22_lora_proxy_train_50x4_2026-05-21_results.json"
)
DEFAULT_OUT_DIR = Path("data/training/wan22_lora_sft_winners_50")


def _load_report(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(path)
    return json.loads(path.read_text())


def _seed_from_label(label: str) -> str:
    match = re.search(r"vid_idx\d{4}", label)
    if not match:
        raise ValueError(f"could not parse BMD seed from label {label!r}")
    return match.group(0)


def _manifest_by_label(report: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {str(row["label"]): row for row in report.get("manifest", [])}


def _rows_by_seed(report: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    by_seed: dict[str, list[dict[str, Any]]] = {}
    for row in report["scores"]:
        by_seed.setdefault(_seed_from_label(str(row["label"])), []).append(row)
    for rows in by_seed.values():
        rows.sort(key=lambda r: float(r["v_mem_projection"]), reverse=True)
    return dict(sorted(by_seed.items()))


def _link_or_copy(src: Path, dst: Path, *, copy: bool, overwrite: bool) -> str:
    if dst.exists():
        if not overwrite:
            return "existing"
        dst.unlink()
    dst.parent.mkdir(parents=True, exist_ok=True)
    if copy:
        shutil.copy2(src, dst)
        return "copy"
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


def _write_dataset_toml(
    path: Path,
    *,
    videos_dir: Path,
    cache_dir: Path,
    resolution: tuple[int, int],
    target_frames: int,
    source_fps: float,
) -> None:
    width, height = resolution
    path.write_text(
        "\n".join(
            [
                "# Auto-generated by scripts/build_wan22_sft_winner_dataset.py",
                "# Video-caption SFT dataset from TRIBE/BMD proxy winner clips.",
                "",
                "[general]",
                f"resolution = [{width}, {height}]",
                'caption_extension = ".txt"',
                "batch_size = 1",
                "enable_bucket = true",
                "bucket_no_upscale = false",
                "",
                "[[datasets]]",
                f'video_directory = "{videos_dir.resolve()}"',
                f'cache_directory = "{cache_dir.resolve()}"',
                f"target_frames = [{target_frames}]",
                'frame_extraction = "head"',
                f"source_fps = {source_fps:.1f}",
                "",
            ]
        )
    )


def _write_sample_prompts(
    path: Path, rows: list[dict[str, Any]], *, frames: int
) -> None:
    lines = [
        "# Auto-generated sample prompts for Musubi Wan I2V training.",
        "# Each --i image is the original BMD seed image used for the generation matrix.",
        "",
    ]
    for row in rows[:8]:
        prompt = str(row["prompt"]).replace("\n", " ").strip()
        image = Path(str(row["seed_image"])).resolve()
        lines.append(
            f"{prompt} --w 640 --h 352 --f {frames} --s 20 --d {row['rank']} --i {image}"
        )
    path.write_text("\n".join(lines) + "\n")


def build_dataset(
    report: dict[str, Any],
    *,
    out_dir: Path,
    project_root: Path,
    resolution: tuple[int, int],
    target_frames: int,
    source_fps: float,
    copy: bool,
    overwrite: bool,
) -> dict[str, Any]:
    manifest = _manifest_by_label(report)
    rows_by_seed = _rows_by_seed(report)
    videos_dir = out_dir / "videos"
    cache_dir = out_dir / "cache_latents"
    cache_text_dir = out_dir / "cache_text"
    out_dir.mkdir(parents=True, exist_ok=True)
    videos_dir.mkdir(parents=True, exist_ok=True)
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_text_dir.mkdir(parents=True, exist_ok=True)

    selected_rows: list[dict[str, Any]] = []
    margins: list[float] = []
    for rank, (seed, score_rows) in enumerate(rows_by_seed.items(), start=1):
        if not score_rows:
            continue
        chosen = score_rows[0]
        chosen_meta = manifest.get(str(chosen["label"]))
        if chosen_meta is None:
            raise KeyError(f"missing manifest row for {chosen['label']!r}")

        src = project_root / str(chosen_meta["local_path"])
        if not src.exists():
            raise FileNotFoundError(src)

        scores = [float(row["v_mem_projection"]) for row in score_rows]
        median_score = float(np.median(scores))
        margin = float(float(chosen["v_mem_projection"]) - median_score)
        margins.append(margin)

        dest_stem = f"{rank:03d}_{seed}_{chosen['label']}"
        dest_video = videos_dir / f"{dest_stem}.mp4"
        link_mode = _link_or_copy(src, dest_video, copy=copy, overwrite=overwrite)
        prompt = str(chosen_meta.get("prompt", "")).replace("\n", " ").strip()
        (videos_dir / f"{dest_stem}.txt").write_text(prompt + "\n")

        selected_rows.append(
            {
                "rank": rank,
                "seed": seed,
                "label": chosen["label"],
                "video": str(dest_video),
                "video_abs": str(dest_video.resolve()),
                "caption_file": str(videos_dir / f"{dest_stem}.txt"),
                "prompt": prompt,
                "seed_image": chosen_meta.get("seed_image"),
                "source_image": chosen_meta.get("source_image"),
                "proxy_score": float(chosen["v_mem_projection"]),
                "seed_median_score": median_score,
                "best_minus_median": margin,
                "bmd_human_memorability_score": chosen_meta.get(
                    "bmd_memorability_score"
                ),
                "source_video": str(src),
                "link_mode": link_mode,
            }
        )

    metadata_jsonl = out_dir / "metadata.jsonl"
    metadata_jsonl.write_text(
        "".join(
            json.dumps(
                {"video_path": row["video_abs"], "caption": row["prompt"]},
                sort_keys=True,
            )
            + "\n"
            for row in selected_rows
        )
    )

    dataset_toml = out_dir / "dataset.toml"
    _write_dataset_toml(
        dataset_toml,
        videos_dir=videos_dir,
        cache_dir=cache_dir,
        resolution=resolution,
        target_frames=target_frames,
        source_fps=source_fps,
    )
    _write_sample_prompts(
        out_dir / "sample_prompts_i2v.txt", selected_rows, frames=target_frames
    )

    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(selected_rows, indent=2))

    summary = {
        "out_dir": str(out_dir),
        "n_winners": len(selected_rows),
        "dataset_toml": str(dataset_toml),
        "metadata_jsonl": str(metadata_jsonl),
        "videos_dir": str(videos_dir),
        "cache_dir": str(cache_dir),
        "cache_text_dir": str(cache_text_dir),
        "sample_prompts_i2v": str(out_dir / "sample_prompts_i2v.txt"),
        "resolution": list(resolution),
        "target_frames": target_frames,
        "source_fps": source_fps,
        "objective": "tribe_bmd_memorability_proxy_sft",
        "warning": "Proxy-selected clips, not direct human labels.",
        "score_mean": float(np.mean([r["proxy_score"] for r in selected_rows]))
        if selected_rows
        else None,
        "best_minus_median_mean": float(np.mean(margins)) if margins else None,
        "best_minus_median_median": float(np.median(margins)) if margins else None,
        "best_minus_median_min": float(np.min(margins)) if margins else None,
        "best_minus_median_max": float(np.max(margins)) if margins else None,
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    (out_dir / "README.md").write_text(
        "\n".join(
            [
                "# Wan2.2 TRIBE/BMD Proxy SFT Winners",
                "",
                "This dataset contains the top TRIBE/BMD-projection Wan2.2 variant for each BMD seed.",
                "It is intended for a tiny LoRA smoke run, not as direct human-preference data.",
                "",
                f"- Winners: {summary['n_winners']}",
                f"- Resolution: {resolution[0]}x{resolution[1]}",
                f"- Target frames: {target_frames}",
                f"- Mean best-minus-median margin: {summary['best_minus_median_mean']:.4f}",
                "",
                "Main files:",
                "- `dataset.toml`: Musubi video-caption dataset config",
                "- `manifest.json`: audit trail for selected clips and scores",
                "- `sample_prompts_i2v.txt`: sample prompts for Wan I2V training/inference",
                "",
            ]
        )
    )
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--project-root", type=Path, default=Path.cwd())
    parser.add_argument("--resolution", nargs=2, type=int, default=(640, 352))
    parser.add_argument("--target-frames", type=int, default=81)
    parser.add_argument("--source-fps", type=float, default=24.0)
    parser.add_argument(
        "--copy",
        action="store_true",
        help="Copy videos instead of hardlinking when possible.",
    )
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    if (args.target_frames - 1) % 4 != 0:
        raise ValueError("--target-frames must be N*4+1 for Wan video training")

    report = _load_report(args.report)
    summary = build_dataset(
        report,
        out_dir=args.out_dir,
        project_root=args.project_root,
        resolution=(args.resolution[0], args.resolution[1]),
        target_frames=args.target_frames,
        source_fps=args.source_fps,
        copy=args.copy,
        overwrite=args.overwrite,
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
