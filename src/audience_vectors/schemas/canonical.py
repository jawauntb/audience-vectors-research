"""Canonical schemas. Every dataset adapter, labeler, and feature job
emits/consumes these so the pipeline stays coherent across sources."""

from __future__ import annotations

from enum import Enum
from typing import Literal

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Label provenance
# ---------------------------------------------------------------------------


class LabelSource(str, Enum):
    """Where a label came from. Never overwrite `HUMAN_ORIGINAL`."""

    HUMAN_ORIGINAL = "human_original"
    DATASET_METADATA = "dataset_metadata"
    SYNTHETIC_VLM = "synthetic_vlm"
    SYNTHETIC_LLM = "synthetic_llm"
    DERIVED_BEHAVIORAL = "derived_behavioral"
    DERIVED_NEURAL = "derived_neural"
    TRIBE_PROJECTION = "tribe_projection"
    ENSEMBLE = "ensemble"


Granularity = Literal["dataset", "video", "segment", "frame"]


class LabelValue(BaseModel):
    """A single label measurement plus provenance.

    Storing raw + z + percentile + value_01 alongside `source` and
    `granularity` is what lets us mix datasets without silently
    treating video-level scores as segment-level truth.
    """

    value: float | None = Field(default=None, description="Canonical 0-1 score.")
    raw_value: float | str | None = Field(default=None, description="Original dataset value, unscaled.")
    z: float | None = Field(default=None, description="Z-score within source dataset.")
    percentile: float | None = Field(default=None, ge=0.0, le=1.0)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    source: LabelSource
    granularity: Granularity = "segment"


# ---------------------------------------------------------------------------
# Videos and segments
# ---------------------------------------------------------------------------

Domain = Literal[
    "ad", "movie", "everyday", "education", "short_form",
    "narrative", "commercial", "lecture", "podcast", "unknown",
]


class CanonicalVideo(BaseModel):
    """One row per source video. Dataset adapters emit these."""

    video_id: str
    source_dataset: str
    media_uri: str
    duration_s: float | None = None
    domain: Domain = "unknown"
    raw_labels: dict[str, float | str | None] = Field(default_factory=dict)
    metadata: dict[str, str | int | float | bool | None] = Field(default_factory=dict)


