class Segment(BaseModel):
    """A short window of one video. The unit of all downstream work."""

    sample_id: str = Field(description="Stable ID: '{source}_{video_id}_seg_{idx:04d}'")
    source_dataset: str
    video_id: str
    domain: Domain = "unknown"
    start_time: float = Field(ge=0.0)
    end_time: float = Field(ge=0.0)
    duration: float = Field(ge=0.0)
    media_path: str | None = None
    audio_path: str | None = None
    frames_path: str | None = None
    transcript: str | None = None
    captions: list[str] = Field(default_factory=list)
    labels: dict[str, LabelValue] = Field(default_factory=dict)
    split: Literal["train", "val", "test", "unassigned"] = "unassigned"

    @property
    def label_sources(self) -> dict[str, LabelSource]:
        return {k: v.source for k, v in self.labels.items()}


# ---------------------------------------------------------------------------
# Personas — synthetic viewer archetypes
# ---------------------------------------------------------------------------


class Persona(BaseModel):
    """A structured viewer archetype. Generate 5-50 of these first; only
    expand to 1000+ persona variants after the base pipeline works."""

    persona_id: str
    cluster: str = Field(description="Archetype family, e.g. 'fast_scroll' or 'cinematic_aesthetic'.")
    attention_weights: dict[str, float] = Field(
        default_factory=dict,
        description="Feature -> weight in [0, 1]. Keys: visual_composition, faces, dialogue, motion, novelty, product_clarity, humor, ...",
    )
    dislikes: dict[str, float] = Field(default_factory=dict)
    story: str = Field(default="", description="Short prose description for VLM prompting.")


class SyntheticLabel(BaseModel):
    """Per-segment label generated by a model (VLM, LLM, ensemble)."""

    segment_id: str
    persona_id: str | None = None
    scores: dict[str, float] = Field(default_factory=dict, description="Bounded to [0, 1].")
    reason: str = ""
    source: LabelSource = LabelSource.SYNTHETIC_VLM
    prompt_version: str = "v1"
    model_id: str | None = None


# ---------------------------------------------------------------------------
# Audience vectors — the research artifact
# ---------------------------------------------------------------------------


class AudienceVector(BaseModel):
    """A contrastive direction in some model's activation space.

    Computed as `mean(activations[high_set]) - mean(activations[low_set])`
    over segments scoring high/low on `target`. Score a new segment by
    projecting its activation onto `direction`.
    """

    vector_id: str
    target: str = Field(description="What this vector predicts, e.g. 'memorability' or 'fast_scroll_attention'.")
    model_id: str = Field(description="Source model, e.g. 'facebook/tribev2'.")
    layer: str = Field(description="Which layer/component the activations came from.")
    direction_uri: str = Field(description="Path to .safetensors/.npy holding the unit-norm direction.")
    dim: int
    positive_set_size: int
    negative_set_size: int
    notes: str = ""
